-- ===========================================================================
--  通過標準的兩個用詞統一
--  2026-09-11
--
--  技能改名之後，全校講的是「打水」和「划手」。有兩句通過標準還留著舊講法，
--  掃過 82 個名稱 + 82 條標準之後就這兩處：
--
--    蝶式（合規）        「無自由式打腿」  → 「無自由式打水」   打水 21 處 : 打腿 1 處
--    初級仰泳 25 碼      「雙臂對稱划水」  → 「雙臂對稱划手」   划手 6 處 : 划水 1 處
--
--  顯示層（db-strings.json）已經改好，家長端和教練端看到的就是新的。這支只是
--  讓資料庫本身跟著一致，免得以後有人直接看資料庫又被舊詞誤導。
--
--  只改字串，不動任何 id、分級或順序。可重複執行。
-- ===========================================================================

BEGIN;

UPDATE public.skills
   SET pass_criteria = replace(pass_criteria, '無自由式打腿', '無自由式打水')
 WHERE pass_criteria LIKE '%無自由式打腿%';

UPDATE public.skills
   SET pass_criteria = replace(pass_criteria, '雙臂對稱划水', '雙臂對稱划手')
 WHERE pass_criteria LIKE '%雙臂對稱划水%';

COMMIT;

